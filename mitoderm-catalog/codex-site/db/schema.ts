import { desc, sql } from "drizzle-orm";
import { check, index, integer, sqliteTable, text } from "drizzle-orm/sqlite-core";

// Anonymous B2B inquiries. Reported professions are not professional verification.
// Contact records have no public read endpoint, and migrations contain no seeds.
export const mitodermLeads = sqliteTable("mitoderm_leads", {
  id: text("id").primaryKey().notNull(),
  requestId: text("request_id").notNull().unique(),
  payloadHash: text("payload_hash").notNull(),
  name: text("name").notNull(),
  phone: text("phone").notNull(),
  profession: text("profession").notNull(),
  productSlug: text("product_slug").notNull(),
  comment: text("comment"),
  locale: text("locale").notNull().default("he"),
  sourceBlock: text("source_block").notNull(),
  privacyConsent: integer("privacy_consent").notNull(),
  privacyVersion: text("privacy_version").notNull(),
  status: text("status").notNull().default("new"),
  createdAt: text("created_at").notNull(),
}, (table) => [
  check("mitoderm_leads_payload_hash_length", sql`length(${table.payloadHash}) = 64`),
  check("mitoderm_leads_name_length", sql`length(${table.name}) BETWEEN 2 AND 100`),
  check("mitoderm_leads_phone_length", sql`length(${table.phone}) BETWEEN 9 AND 16`),
  check("mitoderm_leads_profession", sql`${table.profession} IN ('cosmetologist', 'doctor', 'nurse', 'clinic_owner', 'other')`),
  check("mitoderm_leads_product_slug_length", sql`length(${table.productSlug}) BETWEEN 1 AND 64`),
  check("mitoderm_leads_comment_length", sql`${table.comment} IS NULL OR length(${table.comment}) <= 1000`),
  check("mitoderm_leads_locale", sql`${table.locale} IN ('he', 'ru', 'en')`),
  check("mitoderm_leads_source_block_length", sql`length(${table.sourceBlock}) BETWEEN 1 AND 64`),
  check("mitoderm_leads_privacy_consent", sql`${table.privacyConsent} = 1`),
  index("mitoderm_leads_created_at").on(desc(table.createdAt)),
  index("mitoderm_leads_status_created_at").on(table.status, desc(table.createdAt)),
]);

// The salt is generated by the intake service and stays private to this database.
export const mitodermLeadRateConfig = sqliteTable("mitoderm_lead_rate_config", {
  singleton: integer("singleton").primaryKey(),
  salt: text("salt").notNull(),
}, (table) => [
  check("mitoderm_lead_rate_config_singleton", sql`${table.singleton} = 1`),
  check("mitoderm_lead_rate_config_salt_length", sql`length(${table.salt}) = 64`),
]);

// Pseudonymous, expiring rate counters. Raw client IPs are never stored.
export const mitodermLeadRateLimits = sqliteTable("mitoderm_lead_rate_limits", {
  bucketKey: text("bucket_key").primaryKey().notNull(),
  hits: integer("hits").notNull(),
  expiresAt: integer("expires_at").notNull(),
}, (table) => [
  check("mitoderm_lead_rate_limits_hits", sql`${table.hits} > 0`),
  index("mitoderm_lead_rate_limits_expiry").on(table.expiresAt),
]);
